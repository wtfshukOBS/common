begin;
create index on public.moment_invitations(invited_by);
create index on public.moment_invitations(user_id);
create index on public.moment_join_requests(user_id);
create index on public.moment_messages(author_id,created_at);
create index on public.moment_saves(user_id);
create index on public.notifications(moment_id);
create index on public.reports(moment_id);
create index on public.reports(reporter_id);
