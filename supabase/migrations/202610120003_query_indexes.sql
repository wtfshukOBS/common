alter policy profile_read on public.profiles to authenticated using(not private.blocked((select auth.uid()),id));
alter policy profile_write on public.profiles to authenticated using(id=(select auth.uid())) with check(id=(select auth.uid()));
alter policy settings_read on public.user_settings to authenticated using(user_id=(select auth.uid()));
alter policy settings_write on public.user_settings to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
alter policy moment_read on public.moments to authenticated using(private.visible(id));
alter policy participant_read on public.moment_participants to authenticated using(private.visible(moment_id) and not private.blocked((select auth.uid()),user_id));
alter policy request_read on public.moment_join_requests to authenticated using(user_id=(select auth.uid()) or private.host(moment_id));
alter policy invitation_read on public.moment_invitations to authenticated using(user_id=(select auth.uid()) or private.host(moment_id));
alter policy message_read on public.moment_messages to authenticated using(private.visible(moment_id) and private.member(moment_id) and not private.blocked((select auth.uid()),author_id));
alter policy save_read on public.moment_saves to authenticated using(user_id=(select auth.uid()));
alter policy notification_read on public.notifications to authenticated using(user_id=(select auth.uid()));
alter policy notification_write on public.notifications to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
alter policy block_read on public.user_blocks to authenticated using(user_id=(select auth.uid()));
alter policy connection_read on public.connection_requests to authenticated using((sender_id=(select auth.uid()) or recipient_id=(select auth.uid())) and not private.blocked(sender_id,recipient_id));
alter policy report_read on public.reports to authenticated using(reporter_id=(select auth.uid()));
